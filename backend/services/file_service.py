

import os
import hashlib
import uuid
import mimetypes

from werkzeug.utils import secure_filename
from dotenv import load_dotenv
from supabase import create_client

load_dotenv()


# Allowed document extensions
ALLOWED_EXTENSIONS = {
    "pdf",
    "doc",
    "docx",
    "txt",
    "xlsx",
    "csv"
}


def get_supabase_client():
    """Create a Supabase client using backend environment variables."""

    supabase_url = os.getenv("SUPABASE_URL")
    supabase_key = os.getenv("SUPABASE_SECRET_KEY")

    if not supabase_url or not supabase_key:
        raise RuntimeError(
            "Supabase configuration is missing. "
            "Check SUPABASE_URL and SUPABASE_SECRET_KEY."
        )

    return create_client(supabase_url, supabase_key)


def get_storage_bucket():
    """Get the private Supabase Storage bucket name."""

    bucket = os.getenv("SUPABASE_BUCKET")

    if not bucket:
        raise RuntimeError("SUPABASE_BUCKET is not configured.")

    return bucket


def allowed_file(filename):
    """Check whether the file extension is allowed."""

    if not filename or "." not in filename:
        return False

    extension = filename.rsplit(".", 1)[1].lower()
    return extension in ALLOWED_EXTENSIONS


def generate_file_hash(file_content):
    """Generate a SHA-256 hash from file bytes."""

    return hashlib.sha256(file_content).hexdigest()


def validate_storage_path(storage_path):
    """Accept only simple filenames generated by this service."""

    if (
        not storage_path
        or not isinstance(storage_path, str)
        or storage_path in {".", ".."}
        or "/" in storage_path
        or "\\" in storage_path
    ):
        raise ValueError("Invalid document storage path.")


def save_uploaded_file(uploaded_file, upload_folder=None):
    """
    Upload a document to private Supabase Storage.

    upload_folder is retained for compatibility but is not used.
    """

    if not uploaded_file or not uploaded_file.filename:
        raise ValueError("No file was selected.")

    original_name = secure_filename(uploaded_file.filename)

    if not original_name or "." not in original_name:
        raise ValueError("Invalid filename.")

    if not allowed_file(original_name):
        raise ValueError("File type is not allowed.")

    extension = original_name.rsplit(".", 1)[1].lower()

    file_content = uploaded_file.read()

    if not file_content:
        raise ValueError("The selected file is empty.")

    unique_filename = f"{uuid.uuid4().hex}.{extension}"

    file_hash = generate_file_hash(file_content)

    content_type = (
        mimetypes.guess_type(original_name)[0]
        or "application/octet-stream"
    )

    supabase = get_supabase_client()
    bucket = get_storage_bucket()

    try:
        supabase.storage.from_(bucket).upload(
            path=unique_filename,
            file=file_content,
            file_options={
                "content-type": content_type,
                "upsert": "false"
            }
        )

    except Exception as error:
        raise RuntimeError(
            "Document upload failed. Please try again."
        ) from error

    return {
        "original_name": original_name,
        "storage_name": unique_filename,
        "storage_path": unique_filename,
        "file_path": unique_filename,
        "file_hash": file_hash
    }


def download_file(storage_path):
    """Download a document from Supabase Storage as bytes."""

    validate_storage_path(storage_path)

    supabase = get_supabase_client()
    bucket = get_storage_bucket()

    try:
        return supabase.storage.from_(bucket).download(storage_path)

    except Exception as error:
        raise RuntimeError(
            "Unable to download the document from storage."
        ) from error


def delete_file(storage_path):
    """Delete a document from Supabase Storage."""

    validate_storage_path(storage_path)

    supabase = get_supabase_client()
    bucket = get_storage_bucket()

    try:
        supabase.storage.from_(bucket).remove([storage_path])
        return True

    except Exception as error:
        raise RuntimeError(
            "Unable to delete the document from storage."
        ) from error


def create_document_signed_url(storage_path, expires_in=60):
    """Generate a temporary URL for a private document."""

    validate_storage_path(storage_path)

    if not isinstance(expires_in, int) or expires_in <= 0:
        raise ValueError("Invalid signed URL expiry time.")

    supabase = get_supabase_client()
    bucket = get_storage_bucket()

    try:
        result = supabase.storage.from_(bucket).create_signed_url(
            storage_path,
            expires_in
        )

        return result.get("signedURL") or result.get("signedUrl")

    except Exception as error:
        raise RuntimeError(
            "Unable to generate document access URL."
        ) from error

